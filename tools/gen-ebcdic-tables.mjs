// Generates src/core/ebcdic-tables.ts from the SheetJS `codepage` package (Apache-2.0).
// Only the single-byte EBCDIC code pages Reopen decodes are extracted, so the browser bundle
// stays small (the full codepage table file is ~2 MB).
// Usage: node tools/gen-ebcdic-tables.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const cptable = require('codepage');

const PAGES = [
  [37, 'IBM EBCDIC US-Canada'],
  [20273, 'IBM EBCDIC Germany'],
  [500, 'IBM EBCDIC International'],
  [875, 'IBM EBCDIC Greek Modern'],
  [1026, 'IBM EBCDIC Turkish (Latin 5)'],
  [1047, 'IBM EBCDIC Latin 1/Open System'],
  [1140, 'IBM EBCDIC US-Canada (037 + Euro)'],
  [20290, 'IBM EBCDIC Japanese Katakana Extended'],
];

const lines = [];
for (const [cp, label] of PAGES) {
  // Read the raw byte -> char table. (utils.decode drops unmapped bytes, which would shift indices.)
  const dec = cptable[cp]?.dec;
  if (!dec) throw new Error(`cp${cp}: no table in codepage`);
  let decoded = '';
  for (let b = 0; b < 256; b++) decoded += typeof dec[b] === 'string' && dec[b].length === 1 ? dec[b] : '�';
  if (decoded.length !== 256) throw new Error(`cp${cp}: expected 256 chars, got ${decoded.length}`);
  lines.push(`  ${cp}: { label: ${JSON.stringify(label)}, table: ${JSON.stringify(decoded)} },`);
}

const out = `// GENERATED by tools/gen-ebcdic-tables.mjs. Do not edit by hand.
// Byte -> character tables for single-byte EBCDIC code pages, extracted from the
// SheetJS "codepage" package (https://github.com/SheetJS/js-codepage), Apache-2.0.
// See NOTICE.

export interface EbcdicTable {
  readonly label: string;
  /** 256 characters; index = byte value. */
  readonly table: string;
}

export const EBCDIC_TABLES: Readonly<Record<number, EbcdicTable>> = {
${lines.join('\n')}
};

export const EBCDIC_CODE_PAGES = [${PAGES.map(([cp]) => cp).join(', ')}] as const;
export type EbcdicCodePage = (typeof EBCDIC_CODE_PAGES)[number];
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'core', 'ebcdic-tables.ts');
writeFileSync(target, out, 'utf8');
console.log(`wrote ${target}`);
